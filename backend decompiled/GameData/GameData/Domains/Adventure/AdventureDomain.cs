	private void FillArgBox(AdventureMajorEvent majorEvent, List<ItemKey> costItems)
	{
		if (_runningMajorEventArgBox == null)
		{
			_runningMajorEventArgBox = new EventArgBox();
		}
		_runningMajorEventArgBox.Clear();
		_runningMajorEventArgBox.Set("ConchShipPresetKey_MajorEvent", majorEvent);
		int majorIndex = 0;
		int majorSubIndex = 0;
		int participateIndex = 0;
		int participateSubIndex = 0;
		for (int group = 0; group < majorEvent.Core.Characters.Count; group++)
		{
			AdventureCharacterGroup data = majorEvent.Core.Characters[group];
			bool major = data.Major;
			ref int index = ref major ? ref majorIndex : ref participateIndex;
			ref int subIndex = ref major ? ref majorSubIndex : ref participateSubIndex;
			string key = (major ? "MajorCharacter_" : "ParticipateCharacter_");
			key = key + index + "_";
			IReadOnlyList<int> calledCharacters = majorEvent.QueryCalledCharacters(group);
			_runningMajorEventArgBox.Set(key + "Count", (calledCharacters?.Count ?? 0) + subIndex);
			if (calledCharacters != null && calledCharacters.Count > 0)
			{
				for (int i = 0; i < calledCharacters.Count; i++)
				{
					_runningMajorEventArgBox.Set(key + subIndex++, calledCharacters[i]);
				}
			}
			data.HandleIndex(ref index, ref subIndex);
		}
		int count = costItems?.Count ?? 0;
		_runningMajorEventArgBox.Set("EnterItems_Count", count);
		if (count != 0)
		{
			for (int j = 0; j < count; j++)
			{
				ItemKey item = costItems[j];
				TemplateKey templateKey = new TemplateKey(item.ItemType, item.TemplateId);
				_runningMajorEventArgBox.Set("EnterItems_" + j, templateKey);
			}
		}
	}

	private void TriggerEvent(string guid)
	{
		if (string.IsNullOrEmpty(guid))
		{
			return;
		}
		GameData.Domains.TaiwuEvent.TaiwuEvent taiwuEvent = DomainManager.TaiwuEvent.GetEvent(guid);
		if (taiwuEvent != null)
		{
			EventArgBox prevArgBox = taiwuEvent.ArgBox;
			taiwuEvent.ArgBox = _runningMajorEventArgBox;
			bool conditionPass = taiwuEvent.EventConfig.CheckCondition();
			taiwuEvent.ArgBox = prevArgBox;
			if (conditionPass)
			{
				taiwuEvent.ArgBox = _runningMajorEventArgBox;
				DomainManager.TaiwuEvent.AddTriggeredEvent(taiwuEvent);
				DomainManager.TaiwuEvent.AdventureEventCheckComplete();
			}
		}
	}

