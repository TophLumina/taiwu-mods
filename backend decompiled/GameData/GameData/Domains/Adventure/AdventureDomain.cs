	[SingleValueCollectionDependency(10, new ushort[] { 1 })]
	[SingleValueCollectionDependency(10, new ushort[] { 4 })]
	private void CalcAdventureCache(AdventureCacheData value)
	{
		foreach (AdventureAreaCacheData areaCache in value.BackendAreaCache.Values)
		{
			foreach (AdventureBlockCacheData blockCache in areaCache.BackendBlockCache.Values)
			{
				blockCache.Reset();
			}
		}
		List<short> uselessAreaIds = ObjectPool<List<short>>.Instance.Get();
		uselessAreaIds.Clear();
		uselessAreaIds.AddRange(value.BackendAreaCache.Keys);
		foreach (AdventureRuntime adventure in _adventures.Values)
		{
			short areaId = adventure.MapLocation.AreaId;
			if ((areaId < 0 || areaId >= 141) ? true : false)
			{
				AdaptableLog.Warning($"Generate cache catch unreachable adventure {adventure.Id}");
			}
			else
			{
				uselessAreaIds.Remove(adventure.MapLocation.AreaId);
				value.BackendAreaCache.GetOrNew(adventure.MapLocation.AreaId).BackendBlockCache.GetOrNew(adventure.MapLocation.BlockId).BackendRuntimeIds.Add(adventure.Id);
			}
		}
		foreach (AdventureMajorEvent majorEvent in _adventureMajorEvents.Values)
		{
			short areaId = majorEvent.MapLocation.AreaId;
			if ((areaId < 0 || areaId >= 141) ? true : false)
			{
				AdaptableLog.Warning($"Generate cache catch unreachable major event {majorEvent.Id}");
			}
			else
			{
				uselessAreaIds.Remove(majorEvent.MapLocation.AreaId);
				value.BackendAreaCache.GetOrNew(majorEvent.MapLocation.AreaId).BackendBlockCache.GetOrNew(majorEvent.MapLocation.BlockId).BackendRuntimeIds.Add(majorEvent.Id);
			}
		}
		foreach (short uselessAreaId in uselessAreaIds)
		{
			value.BackendAreaCache.Remove(uselessAreaId);
		}
		ObjectPool<List<short>>.Instance.Return(uselessAreaIds);
		foreach (AdventureAreaCacheData areaCache2 in value.BackendAreaCache.Values)
		{
			foreach (AdventureBlockCacheData blockCache2 in areaCache2.BackendBlockCache.Values)
			{
				blockCache2.BackendRuntimeIds.Sort((int a, int b) => b.CompareTo(a));
			}
		}
	}

