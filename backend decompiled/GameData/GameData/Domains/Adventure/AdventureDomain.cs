	public bool MoveInAdventure(DataContext context, sbyte directionSbyte)
	{
		if (_adventureTaiwu.NotInAdventure || _showingEventInAdventure)
		{
			return false;
		}
		if (!TryGetElement_Adventures(_adventureTaiwu.AdventureId, out var adventure))
		{
			return false;
		}
		AdventureBlockIndex newIndex = _adventureTaiwu.Index.Move((EAdventureDirection)directionSbyte);
		if (!adventure.IsPassable(newIndex))
		{
			return false;
		}
		int requiredActionPoints = adventure.GetMoveCost(newIndex);
		if (!DomainManager.Extra.IsActionPointEnough(requiredActionPoints))
		{
			return false;
		}
		DomainManager.Extra.ConsumeActionPoint(context, requiredActionPoints);
		_adventureTaiwu.SetCurrentIndex(newIndex);
		SetAdventureTaiwu(_adventureTaiwu, context);
		List<AdventureElement> elements = new List<AdventureElement>(adventure.GetElements(newIndex));
		EAdventureChanged changed = TriggerAutoEvents(adventure, EAdventureAutoEventTriggerType.PlayerMove);
		foreach (AdventureElement element in elements.Where(adventure.IsElementAlive))
		{
			changed |= TriggerElementEvents(adventure, element, EAdventureElementEventTriggerType.TaiwuArrivedElement);
		}
		elements.ClearAndAddRange(adventure.GetAllElements());
		if (changed.Contains(EAdventureChanged.EventTriggered) && _showingEventInAdventure)
		{
			_moveContext = (elements, requiredActionPoints);
		}
		else if (PostMove(context, elements, requiredActionPoints))
		{
			changed |= EAdventureChanged.DataChanged;
		}
		if (changed.Contains(EAdventureChanged.DataChanged))
		{
			SetElement_Adventures(adventure.Id, adventure, context);
		}
		return true;
	}

