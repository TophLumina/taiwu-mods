	private AdventureRuntime GenerateAdventure(DataContext context, int coreId, Location location)
	{
		if (!Core.TryGetAdventureData(coreId, out var data) || !location.IsValid())
		{
			return null;
		}
		try
		{
			int id = GetNextAdventureId();
			AdventureRuntime adventure = new AdventureRuntime(id, location, data, context.Random);
			adventure.UpdateStatus(this);
			AddElement_Adventures(id, adventure, context);
			return adventure;
		}
		catch (Exception ex)
		{
			string info = ex.Message + "\nstacktrace" + ex.StackTrace;
			PredefinedLog.Show(40, info);
			return null;
		}
	}

	private int GetNextAdventureId()
	{
		int maxId = ((_adventureMajorEvents.Count != 0) ? _adventureMajorEvents.Keys.Max() : 0);
		maxId = Math.Max(maxId, (_adventures.Count != 0) ? _adventures.Keys.Max() : 0);
		return (maxId == 0) ? 1 : (maxId + 1);
	}

