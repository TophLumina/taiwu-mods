	private bool PostMove(DataContext context, IEnumerable<AdventureElement> elements, int timeCosted)
	{
		if (_adventureTaiwu.NotInAdventure)
		{
			return false;
		}
		AdventureRuntime adventure = GetElement_Adventures(_adventureTaiwu.AdventureId);
		bool anyChanged = _adventureTaiwu.TickState(timeCosted);
		foreach (AdventureElement element in adventure.GetAllElements())
		{
			anyChanged = element.TickState(timeCosted) || anyChanged;
		}
		List<int> actionIds = ObjectPool<List<int>>.Instance.Get();
		adventure.CacheActions(actionIds);
		List<AdventureElement> cache = ObjectPool<List<AdventureElement>>.Instance.Get();
		cache.AddRange(elements);
		bool anyMove = false;
		foreach (AdventureElement element2 in cache.Where(adventure.IsElementAlive))
		{
			if (!adventure.InActionElement(element2))
			{
				int moveTimes = element2.UpdateMove(this, context.Random, adventure, timeCosted);
				anyMove = moveTimes > 0 || anyMove;
				anyChanged = moveTimes >= 0 || anyChanged;
				if (!(element2.Index != _adventureTaiwu.Index))
				{
					EAdventureChanged tag = TriggerElementEvents(adventure, element2, EAdventureElementEventTriggerType.ElementArrivedTaiwu);
					anyChanged = tag.Contains(EAdventureChanged.DataChanged) || anyChanged;
				}
			}
		}
		foreach (int actionId in actionIds)
		{
			anyChanged = ChangeAction(context, adventure, actionId, timeCosted) || anyChanged;
		}
		ObjectPool<List<int>>.Instance.Return(actionIds);
		EventArgBox argBox = DomainManager.TaiwuEvent.GetEventArgBox();
		argBox.Set("ConchShipPresetKey_CostedTime", timeCosted);
		foreach (AdventureElement element3 in cache.Where(adventure.IsElementAlive))
		{
			EAdventureChanged tag2 = TriggerElementEvents(adventure, element3, EAdventureElementEventTriggerType.TimePasses, argBox);
			anyChanged = tag2.Contains(EAdventureChanged.DataChanged) || anyChanged;
		}
		DomainManager.TaiwuEvent.ReturnArgBox(argBox);
		ObjectPool<List<AdventureElement>>.Instance.Return(cache);
		if (anyMove)
		{
			EAdventureChanged tag3 = TriggerAutoEvents(adventure, EAdventureAutoEventTriggerType.ElementMove);
			anyChanged = tag3.Contains(EAdventureChanged.DataChanged) || anyChanged;
		}
		return adventure.UpdateStatus(this) || anyChanged;
	}

	private EAdventureChanged TriggerAutoEvents(AdventureRuntime adventure, EAdventureAutoEventTriggerType triggerType, EventArgBox extraArgBox = null)
	{
		EAdventureChanged result = EAdventureChanged.None;
		RepeatedField<AdventureAutoEventData> autoEvents = adventure.Core.AutoEvents;
		if (autoEvents == null || autoEvents.Count <= 0)
		{
			return result;
		}
		for (int i = 0; i < adventure.Core.AutoEvents.Count; i++)
		{
			AdventureAutoEventData autoEvent = adventure.Core.AutoEvents[i];
			if (autoEvent.TriggerType == triggerType)
			{
				AdventureEventData eventData = autoEvent.Event;
				if (!eventData.OnlyOnce || !adventure.IsInvokedOnceAutoEvent(i))
				{
					EventArgBox argBox = DomainManager.TaiwuEvent.GetEventArgBox();
					extraArgBox?.CloneTo(argBox);
					argBox.Set("ConchShipPresetKey_AdventureId", adventure.Id);
					result |= TriggerEvent(i, eventData, argBox);
				}
			}
		}
		return result;
	}

	private EAdventureChanged TriggerElementEvents(AdventureRuntime adventure, int elementId, EAdventureElementEventTriggerType triggerType, EventArgBox extraArgBox = null)
	{
		AdventureElement element = adventure.GetElement(elementId);
		return TriggerElementEvents(adventure, element, triggerType, extraArgBox);
	}

	private EAdventureChanged TriggerElementEvents(AdventureRuntime adventure, AdventureElement element, EAdventureElementEventTriggerType triggerType, EventArgBox extraArgBox = null)
	{
		EAdventureChanged result = EAdventureChanged.None;
		RepeatedField<AdventureElementEventData> repeatedField = element?.Core.Events;
		if (repeatedField == null || repeatedField.Count <= 0)
		{
			return result;
		}
		int elementId = element.Id;
		for (int i = 0; i < element.Core.Events.Count; i++)
		{
			AdventureElementEventData elementEvent = element.Core.Events[i];
			if (elementEvent.TriggerType == triggerType)
			{
				AdventureEventData eventData = elementEvent.Event;
				if (!eventData.OnlyOnce || !adventure.IsInvokedOnceElementEvent(elementId, i))
				{
					EventArgBox argBox = DomainManager.TaiwuEvent.GetEventArgBox();
					extraArgBox?.CloneTo(argBox);
					argBox.Set("ConchShipPresetKey_AdventureId", adventure.Id);
					argBox.Set("ConchShipPresetKey_ElementId", elementId);
					argBox.Set(EventTriggerParameter.DefValue.CharacterId.ArgBoxKey, element.CharacterId);
					result |= TriggerEvent(i, eventData, argBox);
				}
			}
		}
		return result;
	}

	private EAdventureChanged TriggerEvent(int eventId, AdventureEventData eventData, EventArgBox argBox)
	{
		EAdventureChanged result = EAdventureChanged.None;
		int adventureId = 0;
		if (!argBox.Get("ConchShipPresetKey_AdventureId", ref adventureId))
		{
			return result;
		}
		if (!TryGetElement_Adventures(adventureId, out var adventure))
		{
			return result;
		}
		int elementId = 0;
		if (argBox.Get("ConchShipPresetKey_ElementId", ref elementId) && !adventure.IsElementAlive(elementId))
		{
			return result;
		}
		GameData.Domains.TaiwuEvent.TaiwuEvent taiwuEvent = DomainManager.TaiwuEvent.GetEvent(eventData.Guid);
		if (taiwuEvent == null)
		{
			return result;
		}
		EventArgBox prevArgBox = taiwuEvent.ArgBox;
		taiwuEvent.ArgBox = argBox;
		bool conditionPass = taiwuEvent.EventConfig.CheckCondition();
		taiwuEvent.ArgBox = prevArgBox;
		if (!conditionPass)
		{
			return result;
		}
		if (_showingEventInAdventure && _triggeredEvents.Count >= 1000)
		{
			LogAdventureEventOverflow(eventId, eventData, argBox);
			return result;
		}
		result |= EAdventureChanged.EventTriggered;
		if (_showingEventInAdventure)
		{
			_triggeredEvents.Enqueue((eventId, eventData, argBox));
			return result;
		}
		_showingEventInAdventure = true;
		taiwuEvent.ArgBox = argBox;
		DomainManager.TaiwuEvent.AddTriggeredEvent(taiwuEvent);
		DomainManager.TaiwuEvent.AdventureEventCheckComplete();
		if (!eventData.OnlyOnce)
		{
			return result;
		}
		result |= EAdventureChanged.DataChanged;
		if (elementId == 0)
		{
			adventure.OnceAutoEventInvoked(eventId);
		}
		else
		{
			adventure.OnceElementEventInvoked(elementId, eventId);
		}
		return result;
	}

	public void FinishShowingAdventureEvent(DataContext context)
	{
		int showingEventInAdventure;
		if (!DomainManager.TaiwuEvent.IsShowingEvent)
		{
			List<(string, GameData.Domains.TaiwuEvent.TaiwuEvent)> listeningEventActionList = DomainManager.TaiwuEvent.ListeningEventActionList;
			showingEventInAdventure = ((listeningEventActionList != null && listeningEventActionList.Count > 0) ? 1 : 0);
		}
		else
		{
			showingEventInAdventure = 1;
		}
		_showingEventInAdventure = (byte)showingEventInAdventure != 0;
		if (_processingQueuedEvents)
		{
			return;
		}
		if (!TryGetElement_Adventures(_adventureTaiwu.AdventureId, out var adventure))
		{
			_moveContext = null;
			return;
		}
		bool changed = false;
		int depth = 0;
		_processingQueuedEvents = NeedProcessQueuedEvents;
		while (_processingQueuedEvents)
		{
			(int eventId, AdventureEventData eventData, EventArgBox argBox) tuple = _triggeredEvents.Dequeue();
			int eventId = tuple.eventId;
			AdventureEventData eventData = tuple.eventData;
			EventArgBox argBox = tuple.argBox;
			changed = TriggerEvent(eventId, eventData, argBox).Contains(EAdventureChanged.DataChanged) || changed;
			_processingQueuedEvents = NeedProcessQueuedEvents;
			if (++depth < 1000)
			{
				continue;
			}
			LogAdventureEventOverflow(eventId, eventData, argBox);
			break;
		}
		if (_moveContext.HasValue && !_showingEventInAdventure)
		{
			(IReadOnlyList<AdventureElement>, int) moveContext = _moveContext.Value;
			_moveContext = null;
			changed = PostMove(context, moveContext.Item1, moveContext.Item2) || changed;
		}
		changed = adventure.UpdateStatus(this) || changed;
		if (adventure.InterruptJustRemovedElementActions() || changed)
		{
			SetElement_Adventures(adventure.Id, adventure, context);
		}
		if (!_showingEventInAdventure)
		{
			GameData.GameDataBridge.GameDataBridge.AddDisplayEvent(DisplayEventType.AdventureEventHandled);
		}
	}

