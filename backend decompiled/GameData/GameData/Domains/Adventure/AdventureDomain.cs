	private void AutoGenerateByConfig(DataContext context)
	{
		int date = DomainManager.World.GetCurrDate();
		sbyte month = DomainManager.World.GetCurrMonthInYear();
		Dictionary<short, int> countInAreas = ObjectPool<Dictionary<short, int>>.Instance.Get();
		Stopwatch sw = Stopwatch.StartNew();
		foreach (AdventureGenerateConditionItem config in (IEnumerable<AdventureGenerateConditionItem>)AdventureGenerateCondition.Instance)
		{
			if (config.ForceDisable || !CheckMonthPass(config, month) || (_autoGenerateData.CooldownFinishedDate.TryGetValue(config.TargetId, out var cdDate) && cdDate > date))
			{
				continue;
			}
			IAdventureData data = Core.GetAdventureAny(config.TargetId);
			if (data == null || (data is AdventureData adventureData && !adventureData.AutoGenerateCondition.Check(null)))
			{
				continue;
			}
			IEnumerable<IAdventureRuntime> runtimes = QueryAnyAll(data);
			if (runtimes == null)
			{
				continue;
			}
			countInAreas.Clear();
			foreach (IAdventureRuntime runtime in runtimes)
			{
				if (runtime.CoreId == config.TargetId)
				{
					countInAreas.Accumulate(runtime.MapLocation.AreaId);
				}
			}
			int countInWorld = countInAreas.Values.Sum();
			int maxCount = Math.Min(config.MaxCountInWorld - countInWorld, config.MaxCountInMonth);
			if (maxCount <= 0)
			{
				continue;
			}
			int allowCount = CalcWorldAllowCount(config, countInAreas);
			maxCount = Math.Min(maxCount, allowCount);
			if (maxCount > 0)
			{
				for (int i = 0; i < maxCount; i++)
				{
					AutoGenerateByCache(context, config);
				}
			}
		}
		sw.Stop();
		AdaptableLog.TagWarning("Adventure", $"AutoGenerateByConfig cost {sw.ElapsedMilliseconds}ms");
		ObjectPool<Dictionary<short, int>>.Instance.Return(countInAreas);
	}

	private int CalcWorldAllowCount(AdventureGenerateConditionItem config, Dictionary<short, int> countInAreas)
	{
		int allowCount = 0;
		_autoGenerateStateCache.Clear();
		foreach (List<AdventureGenerateAreaData> cache in _autoGenerateByConfigAreaCache.Values)
		{
			cache.Clear();
		}
		for (int stateIndex = 0; stateIndex < config.StateWeights.Length; stateIndex++)
		{
			int stateWeight = config.StateWeights[stateIndex];
			if (stateWeight <= 0)
			{
				continue;
			}
			int stateTemplateId = 1 + stateIndex;
			MapStateItem stateConfig = MapState.Instance[stateTemplateId];
			sbyte stateId = DomainManager.Map.GetStateIdByStateTemplateId((short)stateTemplateId);
			bool invalidState = true;
			foreach (short areaId in DomainManager.Map.GetRegularAreaIdsInState(stateId))
			{
				EAdventureGenerateAreaWeightType type = CalcGenerateAreaType(stateConfig, areaId);
				int areaWeight = config.AreaWeights[(int)type];
				if (areaWeight > 0)
				{
					int countInArea = countInAreas.GetOrDefault(areaId);
					int areaAllowCount = config.MaxCountInArea - countInArea;
					if (areaAllowCount > 0)
					{
						invalidState = false;
						allowCount += areaAllowCount;
						List<AdventureGenerateAreaData> cache2 = _autoGenerateByConfigAreaCache.GetOrNew(stateId);
						cache2.Add(new AdventureGenerateAreaData(areaId, areaWeight, areaAllowCount));
					}
				}
			}
			if (!invalidState)
			{
				_autoGenerateStateCache.Add(new AdventureGenerateStateData(stateId, stateWeight));
			}
		}
		return allowCount;
	}

	private void AutoGenerateByCache(DataContext context, AdventureGenerateConditionItem config)
	{
		int currDate = DomainManager.World.GetCurrDate();
		int prevCdDate = _autoGenerateData.CooldownFinishedDate.GetOrDefault(config.TargetId);
		int currCdDate = currDate + config.MinInterval;
		if (currCdDate > prevCdDate && currCdDate > currDate)
		{
			_autoGenerateData.CooldownFinishedDate[config.TargetId] = currCdDate;
			SetAutoGenerateData(_autoGenerateData, context);
		}
		int index = RandomUtils.GetRandomIndex(_autoGenerateStateCache, context.Random, SelectStateWeight);
		sbyte stateId = _autoGenerateStateCache[index].StateId;
		List<AdventureGenerateAreaData> cache = _autoGenerateByConfigAreaCache[stateId];
		short areaId = SelectAndReduceAreaAllowCount(context.Random, cache);
		short blockId = GetValidAdventureBlockIdInArea(context.Random, config, areaId);
		if (blockId >= 0)
		{
			IAdventureRuntime runtime = GenerateAny(location: new Location(areaId, blockId), context: context, coreId: config.TargetId);
			if (runtime != null)
			{
				runtime.OfflineHide(context);
				runtime.SetParameter("ConchShipPresetKey_AutoCheckSatisfiedDate", currDate + config.PreparationDuration);
				SetAny(context, runtime);
			}
			if (cache.Count <= 0)
			{
				CollectionUtils.SwapAndRemove(_autoGenerateStateCache, index);
			}
		}
	}

	private short GetValidAdventureBlockIdInArea(IRandomSource random, AdventureGenerateConditionItem config, short areaId)
	{
		List<MapBlockData> pool = ObjectPool<List<MapBlockData>>.Instance.Get();
		Span<MapBlockData> blocks = DomainManager.Map.GetAreaBlocks(areaId);
		Span<MapBlockData> span = blocks;
		for (int i = 0; i < span.Length; i++)
		{
			MapBlockData blockData = span[i];
			if (blockData.IsPassable())
			{
				pool.Add(blockData);
			}
		}
		pool.RemoveAll(QueryAnyAdventureOrMajorEvent);
		EMapBlockType[] includeTypes = config.IncludeTypes;
		if (includeTypes != null && includeTypes.Length > 0)
		{
			pool.RemoveAll((MapBlockData mapBlockData) => !Enumerable.Contains(config.IncludeTypes, mapBlockData.BlockType));
		}
		MapBlockData targetBlock = ((pool.Count > 0) ? pool.GetRandom(random) : null);
		ObjectPool<List<MapBlockData>>.Instance.Return(pool);
		return targetBlock?.BlockId ?? (-1);
	}

