	[DomainMethod]
	public bool EnterMajorEvent(DataContext context, int id, List<ItemKey> costItems)
	{
		if (!TryGetElement_AdventureMajorEvents(id, out var majorEvent))
		{
			return false;
		}
		if (_adventureMajorEventTaiwu.InAdventure)
		{
			return false;
		}
		if (!majorEvent.Core.Cost.IsCostEnough(costItems))
		{
			return false;
		}
		int currentIndex = -1;
		for (int i = 0; i < majorEvent.Core.Nodes.Count; i++)
		{
			AdventureMajorEventNodeData searchingNode = majorEvent.Core.Nodes[i];
			if (searchingNode.Type == EAdventureMajorEventNodeType.Start)
			{
				currentIndex = i;
				break;
			}
		}
		if (currentIndex < 0)
		{
			return false;
		}
		majorEvent.Core.Cost.MakeCost(context, costItems);
		majorEvent.GenerateCharacters(context);
		FillArgBox(majorEvent, costItems);
		AdventureMajorEventNodeData node = majorEvent.Core.Nodes[currentIndex];
		_adventureMajorEventTaiwu.AdventureId = id;
		_adventureMajorEventTaiwu.Current = (_adventureMajorEventTaiwu.CurrentMain = currentIndex);
		_adventureMajorEventTaiwu.UnlockedNodes.ClearAndAddRange(node.NextNodes);
		_adventureMajorEventTaiwu.VisitedNodes.Clear();
		SetAdventureMajorEventTaiwu(_adventureMajorEventTaiwu, context);
		return true;
	}

