	[DomainMethod]
	public bool SelectMajorEvent(DataContext context, int selectedNode)
	{
		if (_adventureMajorEventTaiwu.NotInAdventure)
		{
			return false;
		}
		if (!_adventureMajorEventTaiwu.UnlockedNodes.Contains(selectedNode))
		{
			return false;
		}
		AdventureMajorEvent majorEvent = GetElement_AdventureMajorEvents(_adventureMajorEventTaiwu.AdventureId);
		AdventureMajorEventNodeData node = majorEvent.Core.Nodes[selectedNode];
		_adventureMajorEventTaiwu.Current = selectedNode;
		if (node.Type == EAdventureMajorEventNodeType.Check)
		{
			RepeatedField<int> nextNodes = node.NextNodes;
			if (nextNodes == null || nextNodes.Count <= 0)
			{
				_adventureMajorEventTaiwu.UnlockedNodes.Remove(selectedNode);
				goto IL_00df;
			}
		}
		_adventureMajorEventTaiwu.CurrentMain = selectedNode;
		_adventureMajorEventTaiwu.UnlockedNodes.ClearAndAddRange(majorEvent.Core.Nodes[selectedNode].NextNodes);
		goto IL_00df;
		IL_00df:
		TriggerEvent(node.EventGuid);
		_adventureMajorEventTaiwu.VisitedNodes.Add(_adventureMajorEventTaiwu.Current);
		SetAdventureMajorEventTaiwu(_adventureMajorEventTaiwu, context);
		return true;
	}

